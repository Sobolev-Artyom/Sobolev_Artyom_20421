// Импорт необходимых модулей из стандартной библиотеки
use std::{
    error::Error,  // Базовый трейт для обработки ошибок
    net::{TcpListener},  // Для создания TCP-сервера
};

// Подключение модуля lib из файла lib.rs
mod lib;

// Главная функция, возвращающая Result для обработки ошибок
fn main() -> Result<(), Box<dyn Error>> {
    // Создаем TCP-сервер, слушающий на localhost порт 7878
    // Метод bind() может вернуть ошибку (например, если порт занят),
    // поэтому используем оператор ? для автоматической обработки ошибки
    let listener = TcpListener::bind("127.0.0.1:7878")?;
    
    // Информируем о запуске сервера
    println!("Сервер запущен на 127.0.0.1:7878");

    // Бесконечный цикл для обработки входящих подключений
    for stream_result in listener.incoming() {
        // Обрабатываем результат попытки подключения
        match stream_result {
            // Успешное подключение
            Ok(stream) => {
                println!("Клиент подключён");
                
                // Обрабатываем клиента с помощью функции из модуля lib
                // Если произошла ошибка - печатаем её
                if let Err(e) = lib::handle_client(stream) {
                    eprintln!("Ошибка обработки клиента: {}", e);
                }
                
                println!("Клиент отключён");
            }
            // Ошибка подключения
            Err(e) => eprintln!("Ошибка подключения: {}", e),
        }
    }
    
    // Возвращаем Ok(()) как индикатор успешного выполнения
    Ok(())
}
